# ============================================================
# 文件名：models/__init__.py
# 作用：Python包标识文件，告诉Python这个文件夹是一个可以import的包
# 通俗解释：
#   这个文件本身可以是空的，它的作用就是一个"门牌"。
#   有了这个文件，Python就知道models文件夹是一个"包"，
#   其他文件才能写 from models.anomaly_detection import ... 来导入算法模块。
#   就像一个房间挂了"算法部"的牌子，别人才知道来这里找算法。
# 包含的模块：
#   anomaly_detection.py  —— 孤立森林异常检测（核心技术一）
#   fault_prediction.py   —— 随机森林故障预测（核心技术二）
#   root_cause.py         —— 特征重要度根因分析（核心技术三）
# ============================================================
